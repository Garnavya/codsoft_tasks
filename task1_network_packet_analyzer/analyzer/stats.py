"""Statistical Aggregation and Traffic Profiling Engine.

File: analyzer/stats.py
Purpose: Aggregates captured packet records into traffic intelligence metrics:
protocol distribution, bandwidth totals, top talker IP addresses, and most frequent destination ports.
How it fits: Updated incrementally by packet_analyzer.py and formatted by formatter.py.
Author: CodSoft Cyber Security Intern
How to run: Imported by packet_analyzer.py.

LEARNING NOTE:
In security operations center (SOC) environments and incident response, baseline statistics
reveal anomalies. A sudden spike in UDP traffic may signal DNS amplification DDoS; an influx of
SYN packets to diverse ports indicates port scanning; a single internal IP transmitting
disproportionately large volumes externally suggests data exfiltration.
"""

from collections import Counter
import datetime
from typing import Any, Dict, List, Tuple

from analyzer.protocols import get_service_name


class CaptureStatistics:
    """Aggregates and calculates metrics for a stream of parsed packet records."""

    def __init__(self) -> None:
        """Initialize counters and timers."""
        self.total_packets: int = 0
        self.total_bytes: int = 0
        self.start_time: Optional[datetime.datetime] = None
        self.end_time: Optional[datetime.datetime] = None

        self.protocol_counts: Counter[str] = Counter()
        self.source_ip_counts: Counter[str] = Counter()
        self.dest_ip_counts: Counter[str] = Counter()
        self.dest_port_counts: Counter[int] = Counter()

    def update(self, record: Dict[str, Any]) -> None:
        """Ingest a parsed packet record and increment analytical counters.

        Args:
            record: Normalized dictionary generated by analyzer.parser.parse_packet.
        """
        self.total_packets += 1
        pkt_len = int(record.get("length", 0))
        self.total_bytes += pkt_len

        # Timestamp tracking
        ts_str = record.get("timestamp")
        if ts_str:
            try:
                pkt_time = datetime.datetime.strptime(ts_str, "%Y-%m-%d %H:%M:%S.%f")
                if self.start_time is None or pkt_time < self.start_time:
                    self.start_time = pkt_time
                if self.end_time is None or pkt_time > self.end_time:
                    self.end_time = pkt_time
            except ValueError:
                pass

        # Protocol counts
        proto = record.get("protocol", "OTHER")
        self.protocol_counts[proto] += 1

        # Talker IP counts (ignore unresolved or placeholder N/A)
        src_ip = record.get("src_ip", "N/A")
        dst_ip = record.get("dst_ip", "N/A")
        if src_ip != "N/A":
            self.source_ip_counts[src_ip] += 1
        if dst_ip != "N/A":
            self.dest_ip_counts[dst_ip] += 1

        # Destination port counts
        dst_port = record.get("dst_port")
        if dst_port is not None:
            self.dest_port_counts[dst_port] += 1

    def get_duration_seconds(self) -> float:
        """Calculate the duration between the first and last captured packet in seconds."""
        if self.start_time and self.end_time and self.end_time >= self.start_time:
            return round((self.end_time - self.start_time).total_seconds(), 3)
        return 0.0

    def get_top_source_ips(self, limit: int = 5) -> List[Tuple[str, int]]:
        """Return the top N most active transmitting IP addresses."""
        return self.source_ip_counts.most_common(limit)

    def get_top_destination_ports(self, limit: int = 5) -> List[Tuple[int, str, int]]:
        """Return the top N destination ports with resolved service names and hit counts."""
        top_ports: List[Tuple[int, str, int]] = []
        for port, count in self.dest_port_counts.most_common(limit):
            service = get_service_name(port) or "Custom/Unknown"
            top_ports.append((port, service, count))
        return top_ports

    def to_dict(self) -> Dict[str, Any]:
        """Export statistical summary as a structured dictionary.

        Returns:
            Dictionary containing capture metrics suitable for JSON reporting.
        """
        duration = self.get_duration_seconds()
        avg_rate = round(self.total_packets / duration, 2) if duration > 0 else 0.0

        return {
            "total_packets": self.total_packets,
            "total_bytes": self.total_bytes,
            "duration_seconds": duration,
            "packets_per_second": avg_rate,
            "protocol_breakdown": dict(self.protocol_counts),
            "top_source_ips": [
                {"ip": ip, "count": count}
                for ip, count in self.get_top_source_ips(5)
            ],
            "top_destination_ports": [
                {"port": port, "service": srv, "count": count}
                for port, srv, count in self.get_top_destination_ports(5)
            ],
        }
